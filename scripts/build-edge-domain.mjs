// Bundle the pure reminder rules from src/domain into a Deno-friendly ES module
// so the Edge Function uses exactly the same logic as the app.
import { build } from 'esbuild';

await build({
  stdin: {
    contents: [
      "export { pendingReminders, remindersFor, reminderText, stamp, SNOOZE_MIN, REMINDER_EVENT, notifyOn } from './src/domain/reminders';",
      "export { occKey, splitOccKey } from './src/domain/occurrences';",
      "export { addDays, toMinutes, fromMinutes, toDateStr } from './src/domain/dates';",
      "export { desiredEvents, planSync, gcalEventId } from './src/domain/gcal';",
      "export { buildIcs, zonedToUtc } from './src/domain/ics';",
      "export { migrateTask, isDeadline, dueAtOf, deadlineSnoozeAt, wallDate, wallTime, DEADLINE_SNOOZE_MIN } from './src/domain/deadline';",
    ].join('\n'),
    resolveDir: process.cwd(),
    sourcefile: 'edge-domain.ts',
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  outfile: 'supabase/functions/_shared/domain.js',
  banner: { js: '// GENERATED by scripts/build-edge-domain.mjs — do not edit. Run `npm run build:edge`.' },
  logLevel: 'info',
});
